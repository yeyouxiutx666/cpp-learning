#include <bits/stdc++.h>
using namespace std;


int main()
{
    int a , b ;
    cin >> a >> b ;
    if ( a <= 60 && b <= 60 )
     {
        cout << "no" << endl ;
     }
    else if ( a >= 60 && b >= 60 )
     {
        cout << "no" << endl ;
     }
    else
     {
        cout << "yes" << endl ;
     }

    return 0;
}
